vector<string> SplitList(const char *text) {
	vector<string> out;
	if (!text || !*text) {
		return out;
	}
	for (auto &part : StringUtil::Split(string(text), ',')) {
		StringUtil::Trim(part);
		out.push_back(part);
	}
	return out;
}

