const MarcFunctionDoc *MarcFindFunctionDoc(const string &name) {
	for (auto &doc : FUNCTION_DOCS) {
		if (name == doc.name) {
			return &doc;
		}
	}
	return nullptr;
}

vector<FunctionDescription> MarcFunctionDescriptions(const string &name) {
	vector<FunctionDescription> out;
	auto doc = MarcFindFunctionDoc(name);
	if (!doc) {
		return out;
	}
	// No parameter_types: a single description with none applies to every
	// overload of the function, which is what one entry per name means.
	FunctionDescription description;
	description.parameter_names = SplitList(doc->parameters);
	description.description = doc->description;
	if (doc->example && *doc->example) {
		description.examples.push_back(doc->example);
	}
	description.categories = SplitList(doc->categories);
	out.push_back(std::move(description));
	return out;
}

